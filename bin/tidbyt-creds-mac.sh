#!/usr/bin/env bash
# Mac only: write .local/tidbyt.env for iPhone /setup upload, or POST creds to a setup URL.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LOCAL_DIR="$ROOT/.local"
OUT_FILE="$LOCAL_DIR/tidbyt.env"
UPLOAD_URL=""

usage() {
  cat <<EOF
Usage: tidbyt-creds-mac.sh [--upload SETUP_URL]

  Mac-only helper for P49 Tidbyt creds. Requires TIDBYT_DEVICE_ID and
  TIDBYT_API_TOKEN (env, or sourced from repo .env if present).

  Always writes: ${OUT_FILE}  (gitignored — AirDrop or iCloud to iPhone)

  --upload URL   Also POST to Pi one-time setup (same as /setup page upload).
                 URL from install output, e.g.:
                 http://airplay-beta.local:3003/setup?token=<hex>

Examples:
  export TIDBYT_DEVICE_ID=... TIDBYT_API_TOKEN=...
  ./bin/tidbyt-creds-mac.sh

  ./bin/tidbyt-creds-mac.sh --upload 'http://airplay-beta.local:3003/setup?token=abc...'

  # Then on iPhone: open setup URL → upload .local/tidbyt.env from Files

See docs/p49-tidbyt-credentials.md
EOF
}

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo "tidbyt-creds-mac.sh is Mac-only." >&2
  exit 1
fi

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h | --help)
      usage
      exit 0
      ;;
    -u | --upload)
      UPLOAD_URL="${2:-}"
      if [[ -z "$UPLOAD_URL" ]]; then
        echo "--upload requires a setup URL" >&2
        exit 1
      fi
      shift 2
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

if [[ -f "$ROOT/.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "$ROOT/.env"
  set +a
fi

: "${TIDBYT_DEVICE_ID:?Set TIDBYT_DEVICE_ID (Tidbyt app)}"
: "${TIDBYT_API_TOKEN:?Set TIDBYT_API_TOKEN (Tidbyt app)}"
INSTALLATION_ID="${TIDBYT_INSTALLATION_ID:-airplaystatus}"

mkdir -p "$LOCAL_DIR"
chmod 700 "$LOCAL_DIR"

TIDBYT_DEVICE_ID="$TIDBYT_DEVICE_ID" \
TIDBYT_API_TOKEN="$TIDBYT_API_TOKEN" \
TIDBYT_INSTALLATION_ID="$INSTALLATION_ID" \
OUT_FILE="$OUT_FILE" \
python3 <<'PY'
import os
from pathlib import Path

out = Path(os.environ["OUT_FILE"])
lines = [
    "# Generated by bin/tidbyt-creds-mac.sh — local only, never commit",
    f"TIDBYT_DEVICE_ID={os.environ['TIDBYT_DEVICE_ID']}",
    f"TIDBYT_API_TOKEN={os.environ['TIDBYT_API_TOKEN']}",
    f"TIDBYT_INSTALLATION_ID={os.environ['TIDBYT_INSTALLATION_ID']}",
    "",
]
out.write_text("\n".join(lines), encoding="utf-8")
out.chmod(0o600)
print("Wrote .local/tidbyt.env")
PY

echo ""
echo "Next (iPhone): AirDrop or iCloud .local/tidbyt.env → Files → open Pi /setup URL → upload."
echo ""

if [[ -n "$UPLOAD_URL" ]]; then
  if ! command -v curl >/dev/null; then
    echo "curl required for --upload" >&2
    exit 1
  fi

  echo "Uploading to setup API…"
  UPLOAD_URL="$UPLOAD_URL" OUT_FILE="$OUT_FILE" python3 <<'PY'
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

setup_url = os.environ["UPLOAD_URL"]
content = Path(os.environ["OUT_FILE"]).read_text(encoding="utf-8")
parsed = urllib.parse.urlparse(setup_url)
token = urllib.parse.parse_qs(parsed.query).get("token", [""])[0]
if not token:
    print("Setup URL must include ?token=…", file=sys.stderr)
    sys.exit(1)

base = f"{parsed.scheme}://{parsed.netloc}"
endpoint = f"{base}/api/setup/secrets"
payload = json.dumps({"token": token, "content": content}).encode("utf-8")
req = urllib.request.Request(
    endpoint,
    data=payload,
    headers={"Content-Type": "application/json"},
    method="POST",
)

try:
    with urllib.request.urlopen(req, timeout=30) as resp:
        body = resp.read().decode("utf-8")
except urllib.error.HTTPError as err:
    detail = err.read().decode("utf-8", errors="replace")
    print(f"Upload failed ({err.code}): {detail}", file=sys.stderr)
    sys.exit(1)
except urllib.error.URLError as err:
    print(f"Upload failed: {err.reason}", file=sys.stderr)
    sys.exit(1)

print(body)
try:
    data = json.loads(body)
except json.JSONDecodeError:
    sys.exit(0)

if data.get("ok"):
    tidbyt = data.get("tidbyt", "")
    if tidbyt == "enabled":
        print("Tidbyt enabled on target — play music to push.")
    else:
        print(f"Tidbyt on target: {tidbyt}")
else:
    print(data.get("error", "upload failed"), file=sys.stderr)
    sys.exit(1)
PY
fi
